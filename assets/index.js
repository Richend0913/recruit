  // ========== CM Playback Controller (60 sec / 4 spots / 24 scenes) ==========
  (function() {
    const frame = document.getElementById('cmFrame');
    const ctrl = document.getElementById('cmCtrl');
    const progress = document.getElementById('cmProgress');
    const indicator = document.getElementById('cmSpotIndicator');
    const spotBtns = document.querySelectorAll('.cm-spot-btn');
    if (!frame || !ctrl) return;

    const scenes = frame.querySelectorAll('.cm-scene');

    // Scene start times (ms) — 16 scenes in 60 sec
    // Chapter 1: 0-15s  (4 scenes, 4+4+4+3)
    // Chapter 2: 15-30s (4 scenes, 4+5+4+2)
    // Chapter 3: 30-45s (4 scenes, 4+5+4+2)
    // Chapter 4: 45-60s (4 scenes, 4+5+4+2)
    const sceneStarts = [
      0,     4000,  8000,  12000,    // Ch 1
      15000, 19000, 24000, 28000,    // Ch 2
      30000, 34000, 39000, 43000,    // Ch 3
      45000, 49000, 54000, 58000     // Ch 4
    ];
    const spotBounds = [
      { start: 0,     end: 15000, title: '正直、単価の話。' },
      { start: 15000, end: 30000, title: '1日の流れ。' },
      { start: 30000, end: 45000, title: '紹介が、続く。' },
      { start: 45000, end: 60000, title: 'その先の、話。' }
    ];
    window._cmSpotBounds = spotBounds;
    const totalMs = 60000;

    let rafId = null;
    let startTs = 0;
    let offsetMs = 0;  // Allows seeking from spot buttons
    let playing = false;

    function activateSceneAt(ms) {
      let idx = 0;
      for (let i = 0; i < sceneStarts.length; i++) {
        if (ms >= sceneStarts[i]) idx = i;
      }
      scenes.forEach((s, i) => {
        if (i === idx) {
          if (!s.classList.contains('active')) s.classList.add('active');
        } else {
          s.classList.remove('active');
        }
      });
      // Update spot indicator
      let spotIdx = 0;
      for (let i = 0; i < spotBounds.length; i++) {
        if (ms >= spotBounds[i].start) spotIdx = i;
      }
      if (indicator) indicator.textContent = spotBounds[spotIdx].title;
      spotBtns.forEach((b, i) => {
        b.classList.toggle('active', i === spotIdx);
      });
    }

    function tick(ts) {
      if (!startTs) startTs = ts - offsetMs;
      const elapsed = ts - startTs;

      if (elapsed >= totalMs) {
        progress.style.width = '100%';
        stop();
        return;
      }

      progress.style.width = (elapsed / totalMs * 100) + '%';
      activateSceneAt(elapsed);
      rafId = requestAnimationFrame(tick);
    }

    function play(fromMs) {
      if (rafId) cancelAnimationFrame(rafId);
      playing = true;
      offsetMs = fromMs || 0;
      startTs = 0;
      ctrl.classList.add('hidden');
      scenes.forEach(s => s.classList.remove('active'));
      progress.style.width = (offsetMs / totalMs * 100) + '%';
      setTimeout(() => {
        rafId = requestAnimationFrame(tick);
      }, 30);
    }

    function stop() {
      playing = false;
      if (rafId) cancelAnimationFrame(rafId);
      rafId = null;
      setTimeout(() => {
        ctrl.classList.remove('hidden');
        scenes.forEach(s => s.classList.remove('active'));
        progress.style.width = '0%';
        offsetMs = 0;
      }, 1500);
    }

    ctrl.addEventListener('click', () => play(0));

    // Spot button clicks — jump to that spot's start time
    spotBtns.forEach((btn) => {
      btn.addEventListener('click', () => {
        const spotIdx = parseInt(btn.dataset.spot, 10);
        if (spotBounds[spotIdx]) {
          play(spotBounds[spotIdx].start);
        }
      });
    });

    // Auto-play when CM frame comes into view (once, delayed)
    let autoPlayed = false;
    const cmIO = new IntersectionObserver((entries) => {
      entries.forEach(e => {
        if (e.isIntersecting && !autoPlayed && !playing) {
          autoPlayed = true;
          setTimeout(() => play(0), 400);
        }
      });
    }, { threshold: 0.4 });
    cmIO.observe(frame);
  })();
