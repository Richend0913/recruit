  function setLang(lang) {
    localStorage.setItem('bb_lang', lang);
    const t = TRANSLATIONS[lang];
    if (!t) return;

    document.querySelectorAll('[data-i18n]').forEach(function(el) {
      var key = el.dataset.i18n;
      if (t[key] !== undefined) {
        if (el.hasAttribute('data-i18n-html')) {
          el.innerHTML = t[key];
        } else {
          el.textContent = t[key];
        }
      }
    });

    // Update lang switcher display
    var names = {ja:'JP',en:'EN',vi:'VI',ne:'NE',id:'ID',zh:'中文',ko:'한국'};
    document.querySelector('.lang-switcher button').textContent = '\ud83c\udf10 ' + (names[lang]||lang) + ' \u25be';
    document.getElementById('lang-menu').classList.remove('show');

    // Show/hide foreign-worker-specific sections
    var foreignSections = ['housingSupport', 'visaCheck', 'japaneseLevel', 'taxSupport', 'foreignBenefits'];
    foreignSections.forEach(function(id) {
      var el = document.getElementById(id);
      if (el) {
        if (lang !== 'ja') {
          el.classList.add('i18n-visible');
        } else {
          el.classList.remove('i18n-visible');
        }
      }
    });

    // Update CM spot buttons and indicator
    var spotTitles = [t.cm_spot1_title, t.cm_spot2_title, t.cm_spot3_title, t.cm_spot4_title];
    var spotBtnsAll = document.querySelectorAll('.cm-spot-btn__title[data-i18n]');
    // Also update the JS spotBounds array titles for the CM playback
    if (window._cmSpotBounds) {
      for (var si = 0; si < Math.min(spotTitles.length, window._cmSpotBounds.length); si++) {
        if (spotTitles[si]) window._cmSpotBounds[si].title = spotTitles[si];
      }
    }

    // Populate visa lists
    if (t.visa_types_ok) {
      var okList = document.getElementById('visaOkList');
      if (okList) {
        okList.innerHTML = t.visa_types_ok.map(function(v) { return '<li>' + v + '</li>'; }).join('');
      }
    }
    if (t.visa_types_ng) {
      var ngList = document.getElementById('visaNgList');
      if (ngList) {
        ngList.innerHTML = t.visa_types_ng.map(function(v) { return '<li>' + v + '</li>'; }).join('');
      }
    }
  }

  // Auto-detect on load
  document.addEventListener('DOMContentLoaded', function() {
    var saved = localStorage.getItem('bb_lang');
    if (saved && saved !== 'ja') {
      setLang(saved);
    }
  });

  // Close dropdown when clicking outside
  document.addEventListener('click', function(e) {
    var switcher = document.querySelector('.lang-switcher');
    if (switcher && !switcher.contains(e.target)) {
      document.getElementById('lang-menu').classList.remove('show');
    }
  });

